      <h2>Allgemeine Sicherheitshinweise für Plattformwagen</h2>
      <p>Diese Hinweise gelten für alle Modelle (PLA300-DX, PLA300-DX-SF, PLA300-T2, ST300-DX, TB300-DX, TB300P-DX, TB150-DX) und das Zubehör (PLAB-300):</p>
      <ul>
        <li>Die jeweils angegebene maximale Traglast (150 kg bzw. 300 kg) darf nicht überschritten werden.</li>
        <li>Nicht zur Personenbeförderung geeignet.</li>
        <li>Vor jeder Benutzung auf sichtbare Schäden prüfen (Rollen, Rahmen, Schweißnähte, ggf. Bremse).</li>
        <li>Ausschließlich auf festem, ebenem Untergrund verwenden.</li>
        <li>Last gleichmäßig verteilen; asymmetrische Beladung erhöht die Kippgefahr.</li>
        <li>Feststellbremse PLAB-300 (sofern montiert) beim Beladen und Stehenlassen aktivieren.</li>
        <li>Außerhalb der Reichweite von Kindern aufbewahren und verwenden.</li>
        <li>Bei Beschädigungen sofort außer Betrieb nehmen und vor Weiterbenutzung reparieren lassen.</li>
        <li>Bei Doppeldecker-Modellen (PLA300-T2) maximale Stapelhöhe der oberen Ebene beachten.</li>
      </ul>

